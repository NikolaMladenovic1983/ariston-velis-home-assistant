"""Build all translation outputs from the catalogs in i18n/<lang>.yaml.

    python tools/i18n_build.py            # write the generated files
    python tools/i18n_build.py --check    # exit 1 if a catalog is inconsistent or a generated file is stale

Sources: i18n/en.yaml (reference) + de, fr, it, es, ru, sr-Latn. Serbian Cyrillic (sr) is transliterated
automatically from sr-Latn. Generated (do not edit by hand):
  ha-config/custom_components/ariston_schedule/strings.json + translations/<lang>.json   (HA integration)
  ha-config/custom_components/ariston_schedule/frontend/i18n.js                          (dashboard strategy)
  ha-config/custom_components/ariston_schedule/i18n_data/<lang>.json                     (Excel report)
  ha-config/custom_templates/bojler_i18n.jinja                                           (notifications)
  ha-config/packages/bojler_jezik.yaml                                                   (language selector)
"""
from __future__ import annotations

import json
import pathlib
import re
import sys

import yaml

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = ROOT / "i18n"
COMP = ROOT / "ha-config/custom_components/ariston_schedule"
LANGS = ["en", "de", "fr", "it", "es", "ru", "sr-Latn"]  # sources; "sr" (Cyrillic) is generated
ALL_LANGS = LANGS + ["sr"]
PLACEHOLDER = re.compile(r"\{[a-z_]+\}")

# ---------------------------------------------------------------- Serbian Latin -> Cyrillic
_DIGRAPHS = [("DŽ", "Џ"), ("Dž", "Џ"), ("dž", "џ"), ("LJ", "Љ"), ("Lj", "Љ"), ("lj", "љ"),
             ("NJ", "Њ"), ("Nj", "Њ"), ("nj", "њ")]
_SINGLE = dict(zip("ABVGDĐEŽZIJKLMNOPRSTĆUFHCČŠabvgdđežzijklmnoprstćufhcčš",
                   "АБВГДЂЕЖЗИЈКЛМНОПРСТЋУФХЦЧШабвгдђежзијклмнопрстћуфхцчш"))
# kept in Latin: placeholders, JSON/code samples, paths, brand/unit words, identifiers
_PROTECT = re.compile(
    r"\{[^}]*\}|\[[^\]]*\]|\"[^\"]*\"|/[\w/.-]+|\.xlsx\b|\b\w+\.xlsx\b|\b\w*_\w*\b"
    r"|°C|(?<=\d) ?h\b|\b(?:kWh|Excel|xlsx|BOOST|Boost|Eco|Ariston|NET|Velis|HH:MM|dashboard)\b|(?i:\be-?mail\b)"
)


def to_cyrillic(text: str) -> str:
    out, pos = [], 0
    for m in _PROTECT.finditer(text):
        out.append(_translit(text[pos:m.start()]))
        out.append(m.group(0))
        pos = m.end()
    out.append(_translit(text[pos:]))
    return "".join(out)


def _translit(s: str) -> str:
    for a, b in _DIGRAPHS:
        s = s.replace(a, b)
    return "".join(_SINGLE.get(ch, ch) for ch in s)


def _map_strings(obj, fn):
    if isinstance(obj, dict):
        return {k: _map_strings(v, fn) for k, v in obj.items()}
    if isinstance(obj, str):
        return fn(obj)
    return obj


# ---------------------------------------------------------------- loading + validation
def _flatten(obj, prefix=""):
    if isinstance(obj, dict):
        for k, v in obj.items():
            yield from _flatten(v, f"{prefix}{k}.")
    else:
        yield prefix[:-1], obj


def load() -> dict[str, dict]:
    cats = {lang: yaml.safe_load((SRC / f"{lang}.yaml").read_text(encoding="utf-8")) for lang in LANGS}
    cats["sr"] = _map_strings(cats["sr-Latn"], to_cyrillic)
    cats["sr"]["language_name"] = "Српски"
    return cats


def validate(cats: dict[str, dict]) -> list[str]:
    errors = []
    ref = dict(_flatten(cats["en"]))
    for lang, cat in cats.items():
        flat = dict(_flatten(cat))
        for key in sorted(set(ref) - set(flat)):
            errors.append(f"{lang}: missing key {key}")
        for key in sorted(set(flat) - set(ref)):
            errors.append(f"{lang}: unknown key {key}")
        for key in set(ref) & set(flat):
            if not isinstance(flat[key], str) or not flat[key].strip():
                errors.append(f"{lang}: empty value {key}")
                continue
            if set(PLACEHOLDER.findall(ref[key])) != set(PLACEHOLDER.findall(flat[key])):
                errors.append(f"{lang}: placeholders differ in {key}: {flat[key]!r}")
    return errors


# ---------------------------------------------------------------- outputs
def _json(obj) -> str:
    return json.dumps(obj, ensure_ascii=False, indent=2) + "\n"


def lang_names(cats) -> dict[str, str]:
    return {cats[lang]["language_name"]: lang for lang in ALL_LANGS}


def outputs(cats: dict[str, dict]) -> dict[pathlib.Path, str]:
    out: dict[pathlib.Path, str] = {}
    header = "Generated by tools/i18n_build.py from i18n/*.yaml — do not edit by hand."

    # 1) Home Assistant integration translations
    for lang in ALL_LANGS:
        out[COMP / "translations" / f"{lang}.json"] = _json(cats[lang]["integration"])
    out[COMP / "strings.json"] = _json(cats["en"]["integration"])

    # 2) dashboard strategy catalogs
    js = {lang: {"language_name": cats[lang]["language_name"], "days": cats[lang]["days"],
                 **cats[lang]["dashboard"]} for lang in ALL_LANGS}
    out[COMP / "frontend" / "i18n.js"] = (
        f"// {header}\nexport const CATALOGS = {json.dumps(js, ensure_ascii=False, indent=1)};\n"
    )

    # 3) Excel report texts (backend)
    for lang in ALL_LANGS:
        out[COMP / "i18n_data" / f"{lang}.json"] = _json({"language_name": cats[lang]["language_name"],
                                                           "excel": cats[lang]["excel"], "days": cats[lang]["days"]})

    # 4) Jinja macro for notifications / script messages
    names = lang_names(cats)
    notify = {lang: {**cats[lang]["notify"], **{f"day_{k}": v for k, v in cats[lang]["days"].items()}}
              for lang in ALL_LANGS}
    out[ROOT / "ha-config/custom_templates/bojler_i18n.jinja"] = (
        f"{{# {header}\n"
        "   Usage:  {% from 'bojler_i18n.jinja' import t %}{{ t('ready_msg', {'temp': 55, 'showers': 2}) }}\n"
        "   Language = input_select.bojler_jezik (Settings tab); falls back to English. #}\n"
        "{% macro lang() -%}\n"
        f"{{{{- {json.dumps(names, ensure_ascii=False)}.get(states('input_select.bojler_jezik'), 'en') -}}}}\n"
        "{%- endmacro %}\n"
        "{% macro t(key, p={}) -%}\n"
        f"{{%- set cat = {json.dumps(notify, ensure_ascii=False)} -%}}\n"
        "{%- set c = cat.get(lang(), cat['en']) -%}\n"
        "{%- set ns = namespace(s=c.get(key) or cat['en'].get(key) or key) -%}\n"
        "{%- for k, v in p.items() -%}{%- set ns.s = ns.s.replace('{' ~ k ~ '}', v | string) -%}{%- endfor -%}\n"
        "{{- ns.s -}}\n"
        "{%- endmacro %}\n"
    )

    # 5) language selector helper
    out[ROOT / "ha-config/packages/bojler_jezik.yaml"] = (
        f"# {header}\n"
        "# Language of notifications, script messages and the Excel report. The dashboard itself follows\n"
        "# the language of each user's Home Assistant profile.\n"
        "input_select:\n"
        "  bojler_jezik:\n"
        "    name: Bojler – language / jezik\n"
        "    icon: mdi:translate\n"
        "    options:\n"
        + "".join(f"      - {json.dumps(n, ensure_ascii=False)}\n" for n in names)
    )
    return out


def main() -> int:
    check = "--check" in sys.argv
    cats = load()
    errors = validate(cats)
    if errors:
        print("\n".join(errors))
        return 1
    stale = []
    for path, text in outputs(cats).items():
        current = path.read_text(encoding="utf-8") if path.exists() else None
        if current != text:
            stale.append(path.relative_to(ROOT).as_posix())
            if not check:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(text, encoding="utf-8", newline="\n")
    if check and stale:
        print("stale generated files (run python tools/i18n_build.py):\n  " + "\n  ".join(stale))
        return 1
    print(("up to date" if not stale else "written:\n  " + "\n  ".join(stale)) if not check else "ok")
    return 0


if __name__ == "__main__":
    sys.exit(main())
